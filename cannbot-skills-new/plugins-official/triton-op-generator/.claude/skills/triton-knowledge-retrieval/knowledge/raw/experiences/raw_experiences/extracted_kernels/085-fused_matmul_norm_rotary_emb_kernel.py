@triton.jit
def fused_matmul_norm_rotary_emb_kernel(
    # v_partial_matmul
    MAT_A,
    MAT_B,
    MAT_C,
    M,
    N: tl.constexpr,
    K: tl.constexpr,
    B_STRIDE_K: tl.constexpr,
    B_N_START: tl.constexpr,
    NUM_CORES: tl.constexpr,
    BLOCK_M: tl.constexpr,
    BLOCK_N: tl.constexpr,
    BLOCK_K: tl.constexpr,
    BLOCK_TRESHHOLD: tl.constexpr,
    # k_rmsnorm
    K_INPUT,
    K_WEIGHT,
    K_NORM,
    n_rows,
    eps: tl.constexpr,
    K_DIM: tl.constexpr,
    # q_k_rotary_pos
    Q_INPUT,
    COS,
    SIN,
    Q_EMBED,
    K_EMBED,
    seq_len,
    stride_qs: tl.constexpr,
    stride_qh: tl.constexpr,
    stride_ks: tl.constexpr,
    stride_kh: tl.constexpr,
    DIM_ROPE: tl.constexpr,
    BLOCK_ROPE: tl.constexpr,
    BLOCK_NORM: tl.constexpr,
    NUM_Q_HEADS: tl.constexpr,
    NUM_K_HEADS: tl.constexpr,
):
    # v matmul + k_norm + q_k_rotary_pos
    with dl.async_task(scope=dl.async_task.cube):
        partial_matmul_kernel(
            mat_a=MAT_A,
            mat_b=MAT_B,
            mat_c=MAT_C,
            M=M,
            N=N,
            K=K,
            B_STRIDE_K=B_STRIDE_K,
            B_N_START=B_N_START,
            NUM_CORES=NUM_CORES,
            BLOCK_M=BLOCK_M,
            BLOCK_N=BLOCK_N,
            BLOCK_K=BLOCK_K,
            BLOCK_TRESHHOLD=BLOCK_TRESHHOLD,
        )
    with dl.async_task(scope=dl.async_task.vector):
        rms_norm_block_kernel(
            input=K_INPUT,
            weight=K_WEIGHT,
            output=K_NORM,
            n_rows=n_rows,
            input_row_stride=K_DIM,
            eps=eps,
            N_COLS=K_DIM,
            BLOCK=BLOCK_NORM,
            NUM_CORES=NUM_CORES,
        )
        partial_rotary_emb_kernel(
            Q=Q_INPUT,
            K=K_INPUT,
            COS=COS,
            SIN=SIN,
            Q_EMBED=Q_EMBED,
            K_EMBED=K_EMBED,
            seq_len=seq_len,
            stride_qs=stride_qs,
            stride_qh=stride_qh,
            stride_ks=stride_ks,
            stride_kh=stride_kh,
            DIM=DIM_ROPE,
            BLOCK=BLOCK_ROPE,
            NUM_Q_HEADS=NUM_Q_HEADS,
            NUM_K_HEADS=NUM_K_HEADS,
            NUM_CORES=NUM_CORES,
        )