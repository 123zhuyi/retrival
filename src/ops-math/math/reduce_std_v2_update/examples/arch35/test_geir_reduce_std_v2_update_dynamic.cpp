int CreateGraph(const string& scenarioName, const vector<int64_t>& declaredShape,
                const vector<int64_t>& declaredOutputShape, Graph& graph, vector<Operator>& inputs,
                vector<Operator>& outputs)
{
    auto dataX = AddDataInput("x_" + scenarioName, 0, declaredShape, graph, inputs);
    auto dataMean = AddDataInput("mean_" + scenarioName, 1, declaredShape, graph, inputs);

    auto reduce = op::ReduceStdV2Update(("reduce_std_v2_update_" + scenarioName).c_str());
    reduce.set_input_x(dataX);
    reduce.set_input_mean(dataMean);

    TensorDesc inputDesc(ge::Shape(declaredShape), FORMAT_ND, DT_FLOAT);
    inputDesc.SetFormat(FORMAT_ND);
    inputDesc.SetRealDimCnt(declaredShape.size());
    reduce.update_input_desc_x(inputDesc);
    reduce.update_input_desc_mean(inputDesc);
    reduce.set_attr_dim(vector<int64_t>{-1});
    reduce.set_attr_if_std(false);
    reduce.set_attr_unbiased(true);
    reduce.set_attr_keepdim(false);
    reduce.set_attr_correction(1);

    TensorDesc outputDesc(ge::Shape(declaredOutputShape), FORMAT_ND, DT_FLOAT);
    outputDesc.SetFormat(FORMAT_ND);
    outputDesc.SetRealDimCnt(declaredOutputShape.size());
    reduce.update_output_desc_output_var(outputDesc);

    graph.AddOp(reduce);
    outputs.push_back(reduce);
    graph.SetInputs(inputs).SetOutputs(outputs);
    return SUCCESS;
}

bool ShapeMatches(const vector<int64_t>& expected, const ge::Shape& actual)
{
    if (actual.GetDimNum() != expected.size()) {
        return false;
    }
    for (size_t i = 0; i < expected.size(); ++i) {
        if (actual.GetDim(i) != expected[i]) {
            return false;
        }
    }
    return true;
}

bool VerifyOutput(const ge::Tensor& output, const vector<int64_t>& expectedShape, const vector<float>& golden)
{
    const TensorDesc outputDesc = output.GetTensorDesc();
    if (outputDesc.GetDataType() != DT_FLOAT || !ShapeMatches(expectedShape, outputDesc.GetShape())) {
        return false;
    }
    const size_t expectedBytes = golden.size() * sizeof(float);
    const auto* outputData = reinterpret_cast<const float*>(output.GetData());
    if (outputData == nullptr || output.GetSize() != expectedBytes) {
        std::cout << "Output buffer mismatch: actual bytes=" << output.GetSize() << ", expected bytes=" << expectedBytes
                  << std::endl;
        return false;
    }
    constexpr float kRtol = 1e-4F;
    constexpr float kAtol = 1e-4F;
    for (size_t i = 0; i < golden.size(); ++i) {
        const float error = std::abs(outputData[i] - golden[i]);
        if (!std::isfinite(outputData[i]) || error > kAtol + kRtol * std::abs(golden[i])) {
            std::cout << "Value mismatch at " << i << ": actual=" << outputData[i] << ", expected=" << golden[i]
                      << ", error=" << error << std::endl;
            return false;
        }
    }
    return true;
}

