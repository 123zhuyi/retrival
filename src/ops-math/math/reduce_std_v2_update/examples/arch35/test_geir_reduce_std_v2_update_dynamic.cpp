void PrepareInputAndGolden(const vector<int64_t>& shape, vector<float>& x, vector<float>& mean, vector<float>& golden)
{
    const size_t elementCount = ShapeSize(shape);
    const size_t reduceSize = static_cast<size_t>(shape.back());
    const size_t groupCount = elementCount / reduceSize;
    x.resize(elementCount);
    mean.resize(elementCount);
    golden.resize(groupCount);

    for (size_t group = 0; group < groupCount; ++group) {
        double sum = 0.0;
        for (size_t index = 0; index < reduceSize; ++index) {
            const size_t offset = group * reduceSize + index;
            x[offset] = static_cast<float>(index) * 0.5F + static_cast<float>(group % 7) * 0.125F - 1.0F;
            sum += static_cast<double>(x[offset]);
        }
        const float groupMean = static_cast<float>(sum / static_cast<double>(reduceSize));
        double squareSum = 0.0;
        for (size_t index = 0; index < reduceSize; ++index) {
            const size_t offset = group * reduceSize + index;
            mean[offset] = groupMean;
            const double diff = static_cast<double>(x[offset]) - static_cast<double>(groupMean);
            squareSum += diff * diff;
        }
        golden[group] = static_cast<float>(squareSum / static_cast<double>(reduceSize - 1));
    }
}

