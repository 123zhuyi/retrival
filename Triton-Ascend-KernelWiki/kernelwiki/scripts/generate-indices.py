#!/usr/bin/env python3
from __future__ import annotations

from _common import WIKI_ROOT, pages


SPECS = {
    "by-problem.md": ("problems", "symptoms"),
    "by-technique.md": ("techniques",),
    "by-hardware-feature.md": ("hardware_features",),
    "by-repo.md": ("repo",),
    "by-kernel-type.md": ("kernel_types", "operators"),
}


if __name__ == "__main__":
    corpus = pages()
    (WIKI_ROOT / "queries").mkdir(exist_ok=True)
    legacy_language_index = WIKI_ROOT / "queries" / "by-language.md"
    if legacy_language_index.is_file():
        legacy_language_index.unlink()
    for filename, fields in SPECS.items():
        rows = []
        selected = corpus
        if filename == "by-problem.md":
            selected = [page for page in corpus if page["type"] == "wiki-pattern"]
        elif filename == "by-technique.md":
            selected = [page for page in corpus if page["type"] == "wiki-technique"]
        elif filename == "by-repo.md":
            selected = [page for page in corpus if page["type"] == "source-pr" and page["fm"].get("pr")]
        for page in selected:
            fm = page["fm"]
            for field in fields:
                values = fm.get(field) or []
                values = [values] if isinstance(values, str) else values
                for value in values:
                    rows.append((str(value), str(fm.get("id", "")), str(fm.get("title", "Untitled")), page["type"], page["path"]))
        title = filename.removesuffix(".md").replace("-", " ").title()
        lines = [f"# {title}", "", "<!-- Auto-generated by generate-indices; do not edit manually. -->", "", "| key | page_id | title | type | path |", "|---|---|---|---|---|"]
        lines.extend(f"| {key} | {pid} | {name} | {kind} | {path} |" for key, pid, name, kind, path in sorted(rows))
        output = WIKI_ROOT / "queries" / filename
        output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        print(f"Generated {output.relative_to(WIKI_ROOT).as_posix()}")
