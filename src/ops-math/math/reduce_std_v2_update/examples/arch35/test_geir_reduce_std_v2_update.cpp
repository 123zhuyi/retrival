// ---- CPU golden：var 或 std（double 精度）
static void ComputeGolden(const float* x, const float* mean, float* output, int64_t rows, int64_t cols, int64_t dim,
                          int64_t correction, bool if_std)
{
    if (dim == 1) {
        for (int64_t i = 0; i < rows; ++i) {
            double sqSum = 0;
            for (int64_t j = 0; j < cols; ++j) {
                double diff = static_cast<double>(x[i * cols + j]) - mean[i * cols + j];
                sqSum += diff * diff;
            }
            double var = sqSum / (cols - correction);
            output[i] = static_cast<float>(if_std ? std::sqrt(std::max(var, 0.0)) : var);
        }
    } else {
        for (int64_t j = 0; j < cols; ++j) {
            double sqSum = 0;
            for (int64_t i = 0; i < rows; ++i) {
                double diff = static_cast<double>(x[i * cols + j]) - mean[i * cols + j];
                sqSum += diff * diff;
            }
            double var = sqSum / (rows - correction);
            output[j] = static_cast<float>(if_std ? std::sqrt(std::max(var, 0.0)) : var);
        }
    }
}

