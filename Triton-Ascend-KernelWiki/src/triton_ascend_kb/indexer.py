from __future__ import annotations

from collections import Counter
import hashlib
from pathlib import Path
import re
from typing import Any, Iterable

from .io import atomic_write_text, load_yaml
from .kernelwiki import KernelWikiSearch, Page


INDEX_SPECS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("by-problem.md", ("problems", "symptoms")),
    ("by-technique.md", ("techniques",)),
    ("by-hardware-feature.md", ("hardware_features",)),
    ("by-repo.md", ("repo",)),
    ("by-kernel-type.md", ("kernel_types", "operators")),
)


def _values(value: Any) -> list[str]:
    if value is None:
        return []
    return [value] if isinstance(value, str) else [str(item) for item in value]


def _index_values(page: Page, fields: Iterable[str]) -> list[str]:
    values: list[str] = []
    for field in fields:
        values.extend(_values(page.frontmatter.get(field)))
    return list(dict.fromkeys(value for value in values if value))


def _render_index(title: str, fields: tuple[str, ...], pages: list[Page]) -> str:
    rows: list[tuple[str, str, str, str, str]] = []
    for page in pages:
        for value in _index_values(page, fields):
            rows.append((value, page.id, page.title, page.page_type, page.path))
    lines = [
        f"# {title}",
        "",
        "<!-- Auto-generated by generate-indices; do not edit manually. -->",
        "",
        "| key | page_id | title | type | path |",
        "|---|---|---|---|---|",
    ]
    lines.extend(f"| {key} | {pid} | {title} | {ptype} | {path} |" for key, pid, title, ptype, path in sorted(rows))
    return "\n".join(lines) + "\n"


def build_indices(root: Path) -> list[Path]:
    pages = KernelWikiSearch(root).load_pages()
    query_dir = root / "queries"
    query_dir.mkdir(parents=True, exist_ok=True)
    legacy_language_index = query_dir / "by-language.md"
    if legacy_language_index.is_file():
        legacy_language_index.unlink()
    generated: list[Path] = []
    for filename, fields in INDEX_SPECS:
        path = query_dir / filename
        title = filename.removesuffix(".md").replace("-", " ").title()
        selected = pages
        if filename == "by-problem.md":
            selected = [page for page in pages if page.page_type == "wiki-pattern"]
        elif filename == "by-technique.md":
            selected = [page for page in pages if page.page_type == "wiki-technique"]
        elif filename == "by-repo.md":
            selected = [page for page in pages if page.page_type == "source-pr" and page.frontmatter.get("pr")]
        atomic_write_text(path, _render_index(title, fields, selected))
        generated.append(path)
    return generated


def validate_corpus(root: Path) -> list[str]:
    errors: list[str] = []
    pages = KernelWikiSearch(root).load_pages()
    page_ids: dict[str, str] = {}
    source_ids: set[str] = set()

    for page in pages:
        if not page.id:
            errors.append(f"{page.path}: missing id")
        elif page.id in page_ids:
            errors.append(f"duplicate page id {page.id}: {page_ids[page.id]} and {page.path}")
        else:
            page_ids[page.id] = page.path
        if page.path.startswith("sources/") and page.id:
            source_ids.add(page.id)
        if not page.frontmatter.get("title"):
            errors.append(f"{page.path}: missing title")
        if page.path.startswith("wiki/"):
            if not page.frontmatter.get("type"):
                errors.append(f"{page.path}: wiki page missing type")
            if page.page_type != "wiki-pattern" and not page.frontmatter.get("confidence"):
                errors.append(f"{page.path}: wiki page missing confidence")

    for page in pages:
        if not page.path.startswith("wiki/"):
            continue
        if "source_pages" in page.frontmatter:
            errors.append(f"{page.path}: use canonical 'sources', not legacy 'source_pages'")
        for source_id in _values(page.frontmatter.get("sources")):
            if source_id not in source_ids:
                errors.append(f"{page.path}: unresolved source page {source_id}")

    required_mappings = (
        "data/aliases.yaml",
        "data/architecture-aliases.yaml",
        "data/schemas.yaml",
        "data/tags.yaml",
    )
    for relative in required_mappings:
        path = root / relative
        if not path.exists():
            errors.append(f"{relative}: missing")
        elif not isinstance(load_yaml(path) or {}, dict):
            errors.append(f"{relative}: must be a mapping")

    if not (root / "index.md").is_file():
        errors.append("index.md: missing")
    if not (root / "SKILL.md").is_file():
        errors.append("SKILL.md: missing")

    schemas = load_yaml(root / "data" / "schemas.yaml") or {}
    vocab = load_yaml(root / "data" / "tags.yaml") or {}
    confidence_values = set(_values(vocab.get("confidence")))
    reproducibility_values = list(_values(vocab.get("reproducibility")))
    controlled_fields = (
        "architectures",
        "hardware_features",
        "techniques",
        "kernel_types",
        "symptoms",
    )

    for page in pages:
        if "languages" in page.frontmatter:
            errors.append(f"{page.path}: legacy languages field is not allowed")
        schema = schemas.get(page.page_type) or {}
        for field in schema.get("required", []):
            if field not in page.frontmatter or page.frontmatter[field] in (None, ""):
                errors.append(f"{page.path}: missing required field {field}")
        constraints = schema.get("constraints") or {}
        expected_type = constraints.get("type")
        if expected_type and page.frontmatter.get("type") != expected_type:
            errors.append(f"{page.path}: type must be {expected_type}")
        prefix = constraints.get("id_prefix")
        if prefix and not page.id.startswith(str(prefix)):
            errors.append(f"{page.path}: id must start with {prefix}")
        confidence = page.frontmatter.get("confidence")
        if confidence and confidence not in confidence_values:
            errors.append(f"{page.path}: unknown confidence {confidence}")
        reproducibility = page.frontmatter.get("reproducibility")
        if reproducibility and reproducibility not in reproducibility_values:
            errors.append(f"{page.path}: unknown reproducibility {reproducibility}")
        minimum = constraints.get("reproducibility_minimum")
        if minimum and reproducibility in reproducibility_values:
            if reproducibility_values.index(reproducibility) < reproducibility_values.index(minimum):
                errors.append(f"{page.path}: reproducibility must be at least {minimum}")
        for field in controlled_fields:
            allowed = set(_values(vocab.get(field)))
            for value in _values(page.frontmatter.get(field)):
                if allowed and value not in allowed:
                    errors.append(f"{page.path}: unknown {field} value {value}")

    provenance_schema = schemas.get("artifact-bundle-provenance") or {}
    for provenance_path in sorted((root / "artifacts").rglob("PROVENANCE.yaml")):
        relative = provenance_path.relative_to(root).as_posix()
        data = load_yaml(provenance_path) or {}
        for field in provenance_schema.get("required", []):
            if field not in data:
                errors.append(f"{relative}: missing required field {field}")
        bundle_root = provenance_path.parent
        for record in data.get("files") or []:
            if not isinstance(record, dict):
                errors.append(f"{relative}: each files entry must be a mapping")
                continue
            local_path = record.get("local_path")
            if not local_path:
                errors.append(f"{relative}: files entry missing local_path")
                continue
            artifact = (bundle_root / str(local_path)).resolve()
            try:
                artifact.relative_to(bundle_root.resolve())
            except ValueError:
                errors.append(f"{relative}: local_path escapes bundle: {local_path}")
                continue
            if not artifact.is_file():
                errors.append(f"{relative}: missing artifact file {local_path}")
                continue
            actual = hashlib.sha256(artifact.read_bytes()).hexdigest()
            if record.get("sha256") != actual:
                errors.append(f"{relative}: sha256 mismatch for {local_path}")

    referenced_dirs = {
        str(page.frontmatter["artifact_dir"])
        for page in pages
        if page.frontmatter.get("artifact_dir")
    }
    for artifact_dir in sorted(referenced_dirs):
        path = root / artifact_dir
        if not path.is_dir():
            errors.append(f"{artifact_dir}: artifact_dir missing")
        elif not (path / "PROVENANCE.yaml").is_file():
            errors.append(f"{artifact_dir}: PROVENANCE.yaml missing")

    snapshot_path = root / "data" / "triton-ascend-doc-snapshot.yaml"
    if snapshot_path.is_file():
        snapshot = load_yaml(snapshot_path) or {}
        records = snapshot.get("pages") or []
        if snapshot.get("page_count") != len(records):
            errors.append("data/triton-ascend-doc-snapshot.yaml: page_count mismatch")
        pages_by_path = {page.path: page for page in pages}
        manifest_paths: set[str] = set()
        for record in records:
            if not isinstance(record, dict):
                errors.append("data/triton-ascend-doc-snapshot.yaml: pages entry must be a mapping")
                continue
            local_path = str(record.get("local_path", ""))
            manifest_paths.add(local_path)
            page = pages_by_path.get(local_path)
            if page is None:
                errors.append(f"data/triton-ascend-doc-snapshot.yaml: missing page {local_path}")
                continue
            for field in ("id", "upstream_path", "content_sha256", "snapshot_body_sha256"):
                if str(page.frontmatter.get(field, "")) != str(record.get(field, "")):
                    errors.append(f"{local_path}: manifest {field} mismatch")
            expected_commit = str(snapshot.get("upstream_commit", ""))
            if str(page.frontmatter.get("upstream_commit", "")) != expected_commit:
                errors.append(f"{local_path}: manifest upstream_commit mismatch")
            raw_page = (root / local_path).read_bytes()
            snapshot_body = raw_page.partition(b"\n---\n\n")[2]
            actual_body_hash = hashlib.sha256(snapshot_body).hexdigest()
            if actual_body_hash != record.get("snapshot_body_sha256"):
                errors.append(f"{local_path}: snapshot body sha256 mismatch")
        generated_paths = {
            page.path
            for page in pages
            if page.frontmatter.get("generated_by") == "scripts/ingest_triton_ascend_docs.py"
        }
        for local_path in sorted(generated_paths - manifest_paths):
            errors.append(f"{local_path}: generated doc missing from snapshot manifest")

    taxonomy_path = root / "data" / "operator-taxonomy-sources.yaml"
    if taxonomy_path.is_file():
        taxonomy = load_yaml(taxonomy_path) or {}
        allowed_kernel_types = set(_values(vocab.get("kernel_types")))
        for source in taxonomy.get("sources") or []:
            for category in _values(source.get("categories") if isinstance(source, dict) else None):
                if category not in allowed_kernel_types:
                    errors.append(f"data/operator-taxonomy-sources.yaml: unknown kernel type {category}")

    architecture_aliases_path = root / "data" / "architecture-aliases.yaml"
    if architecture_aliases_path.is_file():
        architecture_aliases = load_yaml(architecture_aliases_path) or {}
        allowed_models = set(_values(vocab.get("architectures")))
        for selector, models in architecture_aliases.items():
            for model in _values(models):
                if model not in allowed_models:
                    errors.append(
                        f"data/architecture-aliases.yaml: selector {selector} has unknown chip model {model}"
                    )

    rules_path = root / "data" / "doc-tagging-rules.yaml"
    if rules_path.is_file():
        rules = load_yaml(rules_path) or {}
        controlled = {
            "architectures": set(_values(vocab.get("architectures"))),
            "hardware_features": set(_values(vocab.get("hardware_features"))),
            "symptoms": set(_values(vocab.get("symptoms"))),
            "kernel_types": set(_values(vocab.get("kernel_types"))),
        }
        for field, allowed in controlled.items():
            for rule in rules.get(field) or []:
                if not isinstance(rule, dict):
                    errors.append(f"data/doc-tagging-rules.yaml: {field} rule must be a mapping")
                    continue
                value = str(rule.get("value", ""))
                if value not in allowed:
                    errors.append(f"data/doc-tagging-rules.yaml: unknown {field} value {value}")
                for regex_field in ("path_regex", "title_regex", "body_regex"):
                    for pattern in rule.get(regex_field) or []:
                        try:
                            re.compile(str(pattern), re.IGNORECASE)
                        except re.error as exc:
                            errors.append(f"data/doc-tagging-rules.yaml: invalid regex {pattern!r}: {exc}")

    architecture_source_path = root / "data" / "npu-architecture-taxonomy-source.yaml"
    if architecture_source_path.is_file():
        architecture_source = load_yaml(architecture_source_path) or {}
        schema = schemas.get("npu-architecture-taxonomy-source") or {}
        for field in schema.get("required", []):
            if field not in architecture_source or architecture_source[field] in (None, ""):
                errors.append(f"data/npu-architecture-taxonomy-source.yaml: missing required field {field}")
        if architecture_source.get("canonical_field") != "architectures":
            errors.append("data/npu-architecture-taxonomy-source.yaml: canonical_field must be architectures")

    governance_path = root / "data" / "tag-governance.yaml"
    if governance_path.is_file():
        governance = load_yaml(governance_path) or {}
        if governance.get("update_mode") != "proposal-only":
            errors.append("data/tag-governance.yaml: update_mode must be proposal-only")
        for field in (governance.get("controlled_fields") or {}):
            if field not in controlled_fields:
                errors.append(f"data/tag-governance.yaml: unknown controlled field {field}")
    return errors


def corpus_status(root: Path) -> list[str]:
    search = KernelWikiSearch(root)
    pages = search.load_pages()
    page_types = Counter(page.page_type for page in pages)
    artifact_modes: Counter[str] = Counter()
    for path in (root / "artifacts").rglob("PROVENANCE.yaml"):
        artifact_modes[str((load_yaml(path) or {}).get("asset_mode", "unknown"))] += 1
    lines = [
        "Corpus counts:",
        f"  Indexed source/wiki pages: {len(pages)}",
        f"  Source PR pages: {page_types['source-pr']}",
        f"  Wiki synthesis pages: {sum(count for kind, count in page_types.items() if kind.startswith('wiki-'))}",
        f"  Doc summaries: {page_types['source-doc']}",
        f"  Evaluation run pages: {page_types['source-run']}",
        f"  Candidate ledgers: {sum(1 for _ in (root / 'candidates').glob('*.yaml'))}",
        f"  Artifact bundles: {sum(artifact_modes.values())}",
        f"  Query indices: {sum(1 for _ in (root / 'queries').glob('*.md'))}",
    ]
    if artifact_modes:
        lines.extend(["", "Artifact bundles by mode:"])
        lines.extend(f"  {mode}: {count}" for mode, count in sorted(artifact_modes.items()))
    return lines
