    slices = tuple(
        slice(int(b), int(e), int(s)) for b, e, s in zip(begin, end, strides)
    )
    value_shape = tmp_var[slices].shape
    value_size = int(np.prod(value_shape)) if len(value_shape) > 0 else 1
    if is_int:
        tmp_value = np.random.randint(-100, 100, size=value_size)
