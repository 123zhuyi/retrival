static constexpr int64_t INDEX_XYZ = 0;
static constexpr int64_t INDEX_CENTER_XYZ = 1;
static constexpr int64_t INDEX_OUTPUT_IDX = 0;
static constexpr int64_t IDX_ATTR_MIN_RADIUS = 0;
static constexpr int64_t IDX_ATTR_MAX_RADIUS = 1;
static constexpr int64_t IDX_ATTR_SAMPLE_NUM = 2;
static constexpr int64_t COORD_DIM = 3;

static ge::graphStatus InferShape4BallQuery(gert::InferShapeContext* context)
{
    OP_LOGD(context->GetNodeName(), "Begin to do InferShape4BallQuery");

    const gert::Shape* xyzShape = context->GetInputShape(INDEX_XYZ);
    OP_CHECK_NULL_WITH_CONTEXT(context, xyzShape);
    const gert::Shape* centerXyzShape = context->GetInputShape(INDEX_CENTER_XYZ);
    OP_CHECK_NULL_WITH_CONTEXT(context, centerXyzShape);
    gert::Shape* idxShape = context->GetOutputShape(INDEX_OUTPUT_IDX);
    OP_CHECK_NULL_WITH_CONTEXT(context, idxShape);

    bool isXyzUnknownRank = Ops::Base::IsUnknownRank(*xyzShape);
    bool isCenterXyzUnknownRank = Ops::Base::IsUnknownRank(*centerXyzShape);

    // xyz 布局 (B,3,N)，坐标在中间维；unknownRank 时跳过维数校验
    if (!isXyzUnknownRank) {
        if (xyzShape->GetDimNum() != 3 || xyzShape->GetDim(1) != COORD_DIM) {
            OP_LOGE(context, "xyz must be (B, 3, N), but got dimNum=%zu", xyzShape->GetDimNum());
            return GRAPH_FAILED;
        }
    }
    // center_xyz 布局 (M,B,3)，坐标在末维；unknownRank 时跳过维数校验
    if (!isCenterXyzUnknownRank) {
        if (centerXyzShape->GetDimNum() != 3 || centerXyzShape->GetDim(2) != COORD_DIM) {
            OP_LOGE(context, "center_xyz must be (M, B, 3), but got dimNum=%zu", centerXyzShape->GetDimNum());
            return GRAPH_FAILED;
        }
    }
    // B 一致校验：unknownRank 或动态 shape(-1) 场景下不参与等值校验
    if (!isXyzUnknownRank && !isCenterXyzUnknownRank) {
        int64_t xyzBatch = xyzShape->GetDim(0);
        int64_t centerXyzBatch = centerXyzShape->GetDim(1);
        if (xyzBatch != -1 && centerXyzBatch != -1 && xyzBatch != centerXyzBatch) {
            OP_LOGE(context, "batch size of xyz(%ld) and center_xyz(%ld) must match", xyzBatch, centerXyzBatch);
            return GRAPH_FAILED;
        }
    }

    // dtype 一致校验
    const auto* xyzDesc = context->GetInputDesc(INDEX_XYZ);
    OP_CHECK_NULL_WITH_CONTEXT(context, xyzDesc);
    const auto* centerXyzDesc = context->GetInputDesc(INDEX_CENTER_XYZ);
    OP_CHECK_NULL_WITH_CONTEXT(context, centerXyzDesc);
    if (xyzDesc->GetDataType() != centerXyzDesc->GetDataType()) {
        OP_LOGE(context, "dtype of xyz and center_xyz must match");
        return GRAPH_FAILED;
    }
    ge::DataType xyzDtype = xyzDesc->GetDataType();
    if (xyzDtype != ge::DT_FLOAT && xyzDtype != ge::DT_FLOAT16) {
        OP_LOGE(context, "xyz dtype must be DT_FLOAT or DT_FLOAT16, but got %d", static_cast<int32_t>(xyzDtype));
        return GRAPH_FAILED;
    }

    auto attrs = context->GetAttrs();
    OP_CHECK_NULL_WITH_CONTEXT(context, attrs);
    const auto* minRadiusPtr = attrs->GetAttrPointer<float>(IDX_ATTR_MIN_RADIUS);
    OP_CHECK_NULL_WITH_CONTEXT(context, minRadiusPtr);
    float minRadius = *minRadiusPtr;
    if (!std::isfinite(minRadius) || minRadius < 0.0f) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "min_radius", std::to_string(minRadius).c_str(),
                                              "min_radius must be finite and >= 0");
        return GRAPH_FAILED;
    }
    const auto* maxRadiusPtr = attrs->GetAttrPointer<float>(IDX_ATTR_MAX_RADIUS);
    OP_CHECK_NULL_WITH_CONTEXT(context, maxRadiusPtr);
    float maxRadius = *maxRadiusPtr;
    if (!std::isfinite(maxRadius) || maxRadius <= 0.0f) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "max_radius", std::to_string(maxRadius).c_str(),
                                              "max_radius must be finite and > 0");
        return GRAPH_FAILED;
    }
    if (maxRadius <= minRadius) {
        OP_LOGE_FOR_INVALID_VALUES_WITH_REASON(context->GetNodeName(), "max_radius, min_radius",
                                               (std::to_string(maxRadius) + ", " + std::to_string(minRadius)).c_str(),
                                               "max_radius must be greater than min_radius");
        return GRAPH_FAILED;
    }
    const auto* sampleNumPtr = attrs->GetAttrPointer<int64_t>(IDX_ATTR_SAMPLE_NUM);
    OP_CHECK_NULL_WITH_CONTEXT(context, sampleNumPtr);
    int64_t sampleNum = *sampleNumPtr;
    if (sampleNum < 1) {
        OP_LOGE(context, "sample_num must >= 1, but got %ld", sampleNum);
        return GRAPH_FAILED;
    }

    // 输出推导：idx.shape = (M, B, sample_num)
    // center_xyz 为 unknownRank 时，M/B 无法推导，但 rank 和 sample_num 已知，设为 {-1, -1, sample_num}
    idxShape->SetDimNum(3);
    if (isCenterXyzUnknownRank) {
        idxShape->SetDim(0, -1); // M 未知
        idxShape->SetDim(1, -1); // B 未知
        OP_LOGD(context->GetNodeName(), "center_xyz is unknown rank, set output to {-1, -1, sample_num}");
    } else {
        idxShape->SetDim(0, centerXyzShape->GetDim(0)); // M
        idxShape->SetDim(1, centerXyzShape->GetDim(1)); // B
    }
    idxShape->SetDim(2, sampleNum); // sample_num

    OP_LOGD(context->GetNodeName(), "End to do InferShape4BallQuery");
    return GRAPH_SUCCESS;
}

