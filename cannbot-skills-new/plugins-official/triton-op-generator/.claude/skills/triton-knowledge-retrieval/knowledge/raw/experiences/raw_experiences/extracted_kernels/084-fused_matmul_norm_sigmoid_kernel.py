@triton.jit
def fused_matmul_norm_sigmoid_kernel(
    MAT_A,
    MAT_B,
    MAT_C,
    M,
    N: tl.constexpr,
    K: tl.constexpr,
    B_STRIDE_K: tl.constexpr,
    B_N_START: tl.constexpr,
    NUM_CORES: tl.constexpr,
    BLOCK_M: tl.constexpr,
    BLOCK_N: tl.constexpr,
    BLOCK_K: tl.constexpr,
    BLOCK_TRESHHOLD: tl.constexpr,
    QQ,
    W,
    O_NORM,
    O_SIGMOID,
    n_rows,
    eps: tl.constexpr,
    DIM: tl.constexpr,
    BLOCK_VEC: tl.constexpr,
):
    with dl.async_task(scope=dl.async_task.cube):
        partial_matmul_kernel(
            mat_a=MAT_A,
            mat_b=MAT_B,
            mat_c=MAT_C,
            M=M,
            N=N,
            K=K,
            B_STRIDE_K=B_STRIDE_K,
            B_N_START=B_N_START,
            NUM_CORES=NUM_CORES,
            BLOCK_M=BLOCK_M,
            BLOCK_N=BLOCK_N,
            BLOCK_K=BLOCK_K,
            BLOCK_TRESHHOLD=BLOCK_TRESHHOLD,
        )
    with dl.async_task(scope=dl.async_task.vector):
        fused_rmsnorm_and_sigmoid_kernel(
            QQ=QQ,
            W=W,
            O_NORM=O_NORM,
            O_SIGMOID=O_SIGMOID,
            n_rows=n_rows,
            eps=eps,
            DIM=DIM,
            BLOCK=BLOCK_VEC,
            NUM_CORES=NUM_CORES,
        )